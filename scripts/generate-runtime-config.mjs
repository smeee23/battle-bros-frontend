import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const frontendRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const option = (name, fallback) => {
  const index = args.indexOf(name);
  return index === -1 ? fallback : args[index + 1];
};

const configPath = path.resolve(frontendRoot, option('--config', process.env.BATTLEBROS_PUBLIC_DATA_CONFIG || 'deployment/public-data.json'));
const outputPath = path.resolve(frontendRoot, option('--output', 'runtime-config.js'));
const deploymentConfig = JSON.parse(fs.readFileSync(configPath, 'utf8'));
const env = process.env;

const manifestPathText = env.BATTLEBROS_DEPLOYMENT_MANIFEST || deploymentConfig.deploymentManifest;
if (!manifestPathText) throw new Error('Missing BATTLEBROS_DEPLOYMENT_MANIFEST or deploymentManifest config.');
const manifestPath = path.resolve(path.dirname(configPath), manifestPathText);
const deploymentManifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));

const chainId = String(env.BATTLEBROS_CHAIN_ID || deploymentConfig.chainId || deploymentManifest.chainId || '');
const battleManager = String(env.BATTLEBROS_BATTLE_MANAGER || deploymentConfig.battleManager || deploymentManifest.battleManager || '').toLowerCase();
const bucket = String(env.BATTLEBROS_S3_BUCKET || deploymentConfig.bucket || '');
const region = String(env.BATTLEBROS_AWS_REGION || env.AWS_REGION || deploymentConfig.region || '');
const prefix = String(env.BATTLEBROS_S3_PREFIX || deploymentConfig.prefix || 'battle-bros').replace(/^\/+|\/+$/g, '');

if (!/^\d+$/.test(chainId)) throw new Error('BattleBros chain ID must be an unsigned decimal integer.');
if (!/^0x[0-9a-f]{40}$/.test(battleManager)) throw new Error('BattleManager must be an Ethereum address.');
if (!bucket && !env.BATTLEBROS_PUBLIC_DATA_ORIGIN && !env.BATTLEBROS_MANIFEST_URL) throw new Error('Missing BattleBros public S3 bucket.');
if (!region && !env.BATTLEBROS_PUBLIC_DATA_ORIGIN && !env.BATTLEBROS_MANIFEST_URL) throw new Error('Missing BattleBros AWS region.');
if (!prefix) throw new Error('BattleBros S3 prefix must not be empty.');

const origin = String(env.BATTLEBROS_PUBLIC_DATA_ORIGIN || deploymentConfig.publicDataOrigin || `https://${bucket}.s3.${region}.amazonaws.com`).replace(/\/+$/, '');
const manifestUrl = String(env.BATTLEBROS_MANIFEST_URL || `${origin}/${prefix}/manifests/${chainId}/${battleManager}/manifest.json`);
const parsedUrl = new URL(manifestUrl);
if (parsedUrl.protocol !== 'https:' && parsedUrl.protocol !== 'http:') throw new Error('BattleBros manifest URL must use HTTP or HTTPS.');

const configuredTokenId = env.BATTLEBROS_DEFAULT_TOKEN_ID ?? deploymentConfig.defaultTokenId;
if (configuredTokenId != null && !/^\d+$/.test(String(configuredTokenId))) throw new Error('Default BattleBro token ID must be an unsigned decimal integer.');

const runtimeConfig = { manifestUrl };
if (configuredTokenId != null) runtimeConfig.tokenId = String(configuredTokenId);
const source = `// Generated by scripts/generate-runtime-config.mjs. Do not edit.\nwindow.__battleBrosPublicData = Object.freeze(${JSON.stringify(runtimeConfig, null, 2)});\n`;
fs.writeFileSync(outputPath, source);
console.log(`runtime config: ${manifestUrl}`);
