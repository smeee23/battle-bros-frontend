import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..'),args=process.argv.slice(2),env=process.env;
const option=(name,fallback)=>{const i=args.indexOf(name);return i<0?fallback:args[i+1];};
const configPath=path.resolve(root,option('--config',env.BATTLEBROS_PUBLIC_DATA_CONFIG||'deployment/public-data.json'));
const config=JSON.parse(fs.readFileSync(configPath,'utf8'));
const deploymentPath=env.BATTLEBROS_DEPLOYMENT_MANIFEST||config.deploymentManifest;
let manifestUrl=env.BATTLEBROS_MANIFEST_URL||config.manifestUrl;
const deployment=!manifestUrl&&deploymentPath?JSON.parse(fs.readFileSync(path.resolve(path.dirname(configPath),deploymentPath),'utf8')):null;
if(deployment && deployment.schemaVersion!==2)throw Error('Only territory deployment manifests are supported');
if(!manifestUrl && deployment){
  const chainId=String(deployment.chainId),combat=String(deployment.combat).toLowerCase();
  if(!/^(0|[1-9][0-9]*)$/.test(chainId)||!/^0x[0-9a-f]{40}$/.test(combat))throw Error('Invalid territory deployment identity');
  const bucket=env.BATTLEBROS_S3_BUCKET||config.bucket,region=env.BATTLEBROS_AWS_REGION||env.AWS_REGION||config.region;
  const origin=env.BATTLEBROS_PUBLIC_DATA_ORIGIN||config.publicDataOrigin||(bucket&&region?`https://${bucket}.s3.${region}.amazonaws.com`:null);
  if(!origin)throw Error('Configure a publication origin or manifest URL');
  const prefix=String(env.BATTLEBROS_S3_PREFIX||config.prefix||'battle-bros').replace(/^\/+|\/+$/g,'');
  manifestUrl=`${origin.replace(/\/+$/,'')}/${prefix}/v2/${chainId}/${combat}/manifest.json`;
}
const runtime={};
if(manifestUrl){
  const parsed=new URL(manifestUrl);
  if(!['http:','https:'].includes(parsed.protocol))throw Error('Manifest URL must use HTTP or HTTPS');
  runtime.schemaVersion=2;runtime.manifestUrl=parsed.href;
  if(deployment)runtime.contracts=Object.fromEntries(['combat','bros','vault','needs'].map(k=>[k,String(deployment[k]).toLowerCase()]));
  const token=env.BATTLEBROS_DEFAULT_TOKEN_ID??config.defaultTokenId;
  if(token!=null){if(!/^(0|[1-9][0-9]*)$/.test(String(token)))throw Error('Invalid default token ID');runtime.tokenId=String(token);}
}
fs.writeFileSync(path.resolve(root,option('--output','runtime-config.js')),'// Generated by scripts/generate-runtime-config.mjs. Do not edit.\nwindow.__battleBrosPublicData = Object.freeze('+JSON.stringify(runtime,null,2)+');\n');
console.log(manifestUrl?`runtime config: ${manifestUrl}`:'runtime config: no deployment configured; local dev uses the latest successful local:e2e run');
